package cz.iocb.load.mona;



/**
 * The SPLASH, the spectral hash identifier, of a spectrum in the JSON export of MoNA.
 */
public class SPLASH
{
    /**
     * The first block of the SPLASH.
     */
    String block1;

    /**
     * The second block of the SPLASH.
     */
    String block2;

    /**
     * The third block of the SPLASH.
     */
    String block3;

    /**
     * The fourth block of the SPLASH.
     */
    String block4;

    /**
     * The whole SPLASH.
     */
    String splash;


    /**
     * Creates an empty SPLASH.
     */
    public SPLASH()
    {
    }
}

package cz.iocb.load.mona;



/**
 * The library of a spectrum in the JSON export of MoNA.
 */
public class Library
{
    /**
     * The description of the library.
     */
    String description;

    /**
     * The name of the library.
     */
    String library;

    /**
     * The link to the spectrum in the library.
     */
    String link;


    /**
     * Creates an empty library.
     */
    public Library()
    {
    }
}
